import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import { describe, expect, it, vi } from 'vitest';
import { TestApp } from '@/test/TestApp';
import { EventForm } from '@/components/EventForm';
import { createEventDraft, eventFromDraft } from '@/lib/event-authoring';
import { draftCreationEvent, PendingDraftPublicationError, readSharedEventDrafts, StaleEventDraftError } from '@/lib/shared-event-drafts';
import { finalizeEvent, generateSecretKey } from 'nostr-tools';

describe('Event Draft form', () => {
  it('explicitly recovers the original signed publication without discarding newer form input', async () => {
    const fields = { ...createEventDraft('Europe/London'), title: 'Original proposal' };
    const result = eventFromDraft(fields, 'recovery');
    if (!result.ok) throw new Error(result.message);
    const signed = finalizeEvent({ ...result.event, created_at: 1 }, generateSecretKey());
    const publish = vi.fn().mockRejectedValue(new PendingDraftPublicationError(signed, 'Publication outcome is uncertain'));
    const recover = vi.fn().mockResolvedValue(undefined);
    const success = vi.fn();
    render(<TestApp><EventForm savedDraft={fields} onPublishDraft={publish} onRecoverPublication={recover} onSuccess={success} /></TestApp>);
    fireEvent.click(screen.getByRole('button', { name: 'Publish Event' }));
    const recovery = await screen.findByRole('button', { name: 'Recover original publication' });
    fireEvent.change(screen.getByLabelText(/Title/), { target: { value: 'Newer input' } });
    fireEvent.change(screen.getByLabelText(/Start Time/), { target: { value: '' } });
    fireEvent.click(recovery);
    await screen.findByText(/Original signed event recovered/);
    expect(recover).toHaveBeenCalledWith(expect.objectContaining({ title: 'Newer input', startTime: '' }));
    expect(screen.getByLabelText(/Title/)).toHaveValue('Newer input');
    expect(success).not.toHaveBeenCalled();
  });
  it('validates before publishing and retains unsaved input after a failed publication', async () => {
    const publish = vi.fn().mockRejectedValue(new Error('Signer declined'));
    const success = vi.fn();
    const fields = { ...createEventDraft('Europe/London'), title: 'Proposal', startDate: '2027-07-12', startTime: '', endDate: '', endTime: '' };
    render(<TestApp><EventForm savedDraft={fields} onPublishDraft={publish} onSaveDraft={vi.fn()} onSuccess={success} /></TestApp>);
    expect(screen.getByRole('button', { name: 'Save draft' })).toBeEnabled();
    const submit = screen.getByRole('button', { name: 'Publish Event' });
    fireEvent.submit(submit.closest('form')!);
    await screen.findByText('Start date and time are required');
    expect(publish).not.toHaveBeenCalled();
    fireEvent.change(screen.getByLabelText(/Start Time/), { target: { value: '09:00' } });
    fireEvent.change(screen.getByLabelText(/Title/), { target: { value: 'Unsaved title' } });
    fireEvent.click(submit);
    await screen.findByText(/Signer declined/);
    expect(publish).toHaveBeenCalledWith(expect.objectContaining({ title: 'Unsaved title', tzid: 'Europe/London' }));
    expect(screen.getByLabelText(/Title/)).toHaveValue('Unsaved title');
    expect(success).not.toHaveBeenCalled();
    publish.mockResolvedValue(undefined);
    fireEvent.click(submit);
    await waitFor(() => expect(success).toHaveBeenCalledOnce());
  });
  it('requires confirmation, cancels without deleting, and retains input after a failed deletion', async () => {
    const remove = vi.fn().mockRejectedValue(new Error('Acknowledgment timed out'));
    const success = vi.fn();
    render(<TestApp><EventForm savedDraft={{ ...createEventDraft('Europe/London'), title: 'Proposal' }} onDeleteDraft={remove} onSuccess={success} /></TestApp>);
    expect(remove).not.toHaveBeenCalled();
    fireEvent.change(screen.getByLabelText(/Title/), { target: { value: 'Unsaved title' } });
    fireEvent.click(screen.getByRole('button', { name: 'Delete draft' }));
    expect(screen.getByRole('alertdialog')).toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }));
    expect(remove).not.toHaveBeenCalled();
    expect(screen.getByLabelText(/Title/)).toHaveValue('Unsaved title');
    fireEvent.click(screen.getByRole('button', { name: 'Delete draft' }));
    fireEvent.click(screen.getByRole('button', { name: 'Confirm deletion' }));
    await screen.findByText(/Acknowledgment timed out.*Check your signer and relay connections.*same signed deletion/);
    expect(success).not.toHaveBeenCalled();
    expect(screen.getByLabelText(/Title/)).toHaveValue('Unsaved title');
    remove.mockResolvedValue(undefined);
    fireEvent.click(screen.getByRole('button', { name: 'Confirm deletion' }));
    await waitFor(() => expect(success).toHaveBeenCalledOnce());
  });
  it.each(['Save draft', 'Publish Event'])('retains unsaved input for reconciliation after a stale %s', async (action) => {
    const fields = { ...createEventDraft('Europe/London'), title: 'Original', content: 'Original notes' };
    const record = finalizeEvent({ ...draftCreationEvent({ ...fields, title: 'Remote title' }), created_at: 1 }, generateSecretKey());
    const latest = readSharedEventDrafts([record], [record.pubkey])[0];
    const save = vi.fn().mockRejectedValue(new StaleEventDraftError(latest));
    const load = vi.fn();
    render(<TestApp><EventForm savedDraft={fields} onSaveDraft={save} onPublishDraft={save} onLoadLatestDraft={load} /></TestApp>);
    expect(screen.getByLabelText(/Title/)).toBeEnabled();
    fireEvent.change(screen.getByLabelText(/Title/), { target: { value: 'My unsaved title' } });
    fireEvent.click(screen.getByRole('button', { name: action }));
    await screen.findByRole('button', { name: 'Load latest draft' });
    expect(screen.getByRole('button', { name: 'Publish Event' })).toBeDisabled();
    expect(screen.getByLabelText(/Title/)).toHaveValue('My unsaved title');
    fireEvent.click(screen.getByRole('button', { name: 'Load latest draft' }));
    expect(load).toHaveBeenCalledWith(latest);
    expect(screen.getByLabelText(/Title/)).toHaveValue('Remote title');
    expect(screen.getByLabelText<HTMLTextAreaElement>('Your unsaved fields').value).toContain('My unsaved title');
    expect(screen.getByLabelText('Timezone')).toHaveTextContent('Europe/London');
  });
  it('reopens saved fields including their timezone without publishing or consuming', () => {
    const fields = { ...createEventDraft('Europe/London'), title: 'Shared proposal', startDate: '', content: 'Keep these notes' };
    const success = vi.fn();
    render(<TestApp><EventForm savedDraft={fields} onSuccess={success} onCancel={() => {}} /></TestApp>);
    expect(screen.getByLabelText(/Title/)).toHaveValue('Shared proposal');
    expect(screen.getByLabelText(/Full Description/)).toHaveValue('Keep these notes');
    expect(screen.getByLabelText('Timezone')).toHaveTextContent('Europe/London');
    expect(screen.getByLabelText(/Start Date/)).toHaveValue('');
    expect(screen.queryByRole('button', { name: 'Publish Event' })).not.toBeInTheDocument();
    expect(success).not.toHaveBeenCalled();
  });
  it('saves with only a title and retains input when saving fails', async () => {
    const save = vi.fn().mockRejectedValue(new Error('Relay unavailable'));
    const success = vi.fn();
    render(<TestApp><EventForm onSaveDraft={save} onSuccess={success} /></TestApp>);
    fireEvent.change(screen.getByLabelText(/Title/), { target: { value: 'Unscheduled proposal' } });
    for (const label of ['Start Date', 'Start Time', 'End Date', 'End Time']) {
      fireEvent.change(screen.getByLabelText(new RegExp(label)), { target: { value: '' } });
    }
    fireEvent.click(screen.getByRole('button', { name: 'Save draft' }));
    await waitFor(() => expect(save).toHaveBeenCalledWith(expect.objectContaining({ title: 'Unscheduled proposal', startDate: '', startTime: '' })));
    expect(screen.getByLabelText(/Title/)).toHaveValue('Unscheduled proposal');
    expect(success).not.toHaveBeenCalled();
    save.mockResolvedValue(undefined);
    fireEvent.click(screen.getByRole('button', { name: 'Save draft' }));
    await waitFor(() => expect(success).toHaveBeenCalledOnce());
  });
});
